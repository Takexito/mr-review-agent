import { contextSection, coverageFields, diffSection, outOfScopeSection, type DiffPromptInput } from './prompts.js';

export const STANDARDS_BEGIN = '=== BEGIN_STANDARDS_JSON ===';
export const STANDARDS_END = '=== END_STANDARDS_JSON ===';

export interface StandardsPromptInput extends DiffPromptInput {
  readonly projectPath: string;
  readonly sourceBranch: string;
  readonly targetBranch: string;
  /** Существующие треды MR (для дедупа). Пусто = нет. */
  readonly existingThreads?: string;
  readonly contextHints?: readonly string[];
  readonly declaredStandards?: readonly string[];
}

/**
 * Базовый набор запахов (Фаулер, «Рефакторинг», гл. 3): действует и там, где репозиторий
 * ничего не документирует. Формат строки — «что это → как чинить».
 */
const SMELL_BASELINE: readonly string[] = [
  'Mysterious Name: имя функции, переменной или типа не раскрывает, что она делает или хранит. → переименовать; если честное имя не находится — мутен сам дизайн.',
  'Duplicated Code: одна и та же форма логики в нескольких hunk-ах или файлах изменения. → вынести общую форму, звать из обоих мест.',
  'Feature Envy: метод лезет в данные чужого объекта чаще, чем в свои. → перенести метод к данным, которым он завидует.',
  'Data Clumps: одни и те же несколько полей или параметров ходят вместе. → собрать их в один тип и передавать его.',
  'Primitive Obsession: примитив или строка стоит на месте доменного понятия, заслуживающего своего типа. → дать понятию небольшой собственный тип.',
  'Repeated Switches: один и тот же `when`/`if`-каскад по одному типу повторяется в изменении. → полиморфизм или одна общая таблица.',
  'Shotgun Surgery: одно логическое изменение размазано правками по многим файлам диффа. → собрать то, что меняется вместе, в один модуль.',
  'Divergent Change: один файл или модуль правится по нескольким не связанным причинам. → разделить так, чтобы у модуля была одна причина меняться.',
  'Speculative Generality: абстракция, параметры или хуки под потребности, которых у задачи нет. → удалить, заинлайнить до появления реальной потребности.',
  'Message Chains: длинная навигация `a.b().c().d()`, от которой вызывающий не должен зависеть. → спрятать обход за одним методом первого объекта.',
  'Middle Man: класс или функция в основном только делегирует дальше. → убрать, звать настоящую цель напрямую.',
  'Refused Bequest: наследник или реализация игнорирует или переопределяет большую часть унаследованного. → заменить наследование композицией.',
];

function threadsSection(existingThreads: string | undefined): string[] {
  if (!existingThreads || existingThreads.trim().length === 0) return [];
  return [
    '',
    'УЖЕ ОБСУЖДЕНО В ЭТОМ MR:',
    existingThreads.trim(),
    '',
    'В "violations" и "smells" идут только находки, которых в тредах выше ещё нет. Ответ автора «уже починил»',
    'сверь с текущим кодом: правки нет — подними снова со ссылкой на тред.',
  ];
}

export function buildStandardsPrompt(input: StandardsPromptInput): string {
  const base = input.baseSha ?? '<base>';
  return [
    'Ты ревьюер merge request по оси СТАНДАРТЫ: следует ли изменение задокументированным стандартам этого репозитория.',
    'Баги и соответствие постановке — оси других ревьюеров.',
    `Проект: ${input.projectPath}. Ветка ${input.sourceBranch} → ${input.targetBranch}.`,
    'Репозиторий выкачан в рабочую директорию.',
    '',
    'НАРУШЕНИЕ — регрессия против живого требования. Запись в "violations" держится на трёх доказательствах:',
    '- Требование. Документ обязывает: в тексте правила стоит must / never / always / «обязан» / «запрещено».',
    '  Дословная цитата идёт в "quote". Типовое решение, пример и таблица рецептов — рекомендации: они помогают читать код.',
    '- Живое. Проект сам этому правилу следует: в коде, существовавшем до MR, есть место, где оно соблюдено;',
    '  путь к нему идёт в "precedent". Правило, которому проект нигде не следует, — мёртвая буква: его место в "deadLetters".',
    `- Регрессия. Отступление внёс этот MR: строка добавлена диффом, а в базовой версии файла (\`git show ${base}:<файл>\`) его не было.`,
    'Когда документы расходятся, прав тот, что написан про этот проект (`AGENTS.md`, `CONTEXT.md`, `docs/`).',
    '',
    'ШАГ 1 — СОБЕРИ СТАНДАРТЫ.',
    'Стандарт — документ репозитория о том, КАК здесь пишут код: `AGENTS.md` и `CLAUDE.md` (в корне и в каталогах',
    'изменённых файлов), `CONTEXT.md`, `CONTRIBUTING.md`, `docs/adr/`, `docs/guides/`, руководства по тестам, скиллы агентов.',
    'Найди их поиском по репозиторию и прочитай те, что касаются изменённых модулей.',
    ...(input.declaredStandards && input.declaredStandards.length > 0
      ? [
          `Проект сам назвал своими стандартами (\`.review.yml\`): ${input.declaredStandards.map((d) => `\`${d}\``).join(', ')} — прочитай их первыми и целиком,`,
          // В worktree лежит head MR: оттуда автор MR переписал бы объявленный стандарт в том же MR.
          `версию из target-ветки: \`git show ${input.targetBranch}:<путь>\`.`,
        ]
      : []),
    'Конфиги линтеров и форматтеров (detekt, lint, `.editorconfig`, CI) прочитай отдельно — по ним видно, что ловит инструмент.',
    'Документы вроде `AGENTS.md` написаны для агента, который пишет код: указания о том, как вести работу, что спрашивать',
    'и какие команды запускать, к готовому коду не относятся. Сверяй только требования к самому коду.',
    'Шаг завершён, когда каждый найденный документ либо прочитан и записан в "standardsRead", либо отброшен как не относящийся к изменённому коду.',
    '',
    'ШАГ 2 — ПРОЙДИ ДИФФ.',
    'Каждый hunk сверь с требованиями из шага 1; найдя отступление, собери по нему три доказательства.',
    'Шаг завершён, когда каждый изменённый файл сверен, а у каждой записи в "violations" заполнены "quote" и "precedent".',
    '',
    'ШАГ 3 — ЗАПАХИ.',
    'Пройди дифф по базовому набору ниже. Запах — оценочное суждение: формулируй как «возможно, <запах>» и объясняй, чем он здесь мешает.',
    'Правило репозитория сильнее базового набора: то, что документ одобряет, запахом не считается.',
    ...outOfScopeSection(),
    '',
    'БАЗОВЫЙ НАБОР ЗАПАХОВ (что это → как чинить):',
    ...SMELL_BASELINE.map((s) => `- ${s}`),
    ...contextSection(input.contextHints),
    ...threadsSection(input.existingThreads),
    '',
    `Верни РОВНО один JSON между маркерами ${STANDARDS_BEGIN} и ${STANDARDS_END}, без текста вокруг:`,
    STANDARDS_BEGIN,
    '{',
    '  "summary": "краткий вывод по оси стандартов (markdown, 1-4 предложения)",',
    '  "standardsRead": ["AGENTS.md", "docs/testing-guide.md"],',
    ...coverageFields(input.diffMode),
    '  "violations": [',
    '    { "path": "относительный/путь.kt", "line": 42, "standard": "AGENTS.md › Critical Rules › 2. LCE Pattern",',
    '      "quote": "дословная цитата требования", "precedent": "путь/к/коду/где/соблюдено.kt:10", "body": "что нарушено и как исправить" }',
    '  ],',
    '  "deadLetters": [',
    '    { "standard": "документ › раздел", "note": "что требует документ и как на самом деле устроен проект" }',
    '  ],',
    '  "smells": [',
    '    { "smell": "Feature Envy", "path": "относительный/путь.kt", "line": 42, "body": "возможно, …: чем мешает и как чинить" }',
    '  ]',
    '}',
    STANDARDS_END,
    'Поле "line" — номер строки в НОВОЙ версии файла. Пустой массив — нормальный ответ для любого из трёх списков.',
    ...diffSection(input),
  ].join('\n');
}
