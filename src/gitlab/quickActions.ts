/**
 * GitLab исполняет строку заметки, начинающуюся с `/команда` (`/merge`, `/approve`, `/close`),
 * от имени автора заметки — то есть бота. Текст заметок приходит от агента, а на него влияет
 * содержимое MR и задач, поэтому такая строка в ответе превращает prompt injection в действие
 * с правами бота.
 *
 * Экранируется каждая такая строка, включая строки внутри блоков кода: GitLab считает блоком
 * только корректно закрытый fence, и незакрытый или вложенный fence в ответе агента иначе
 * оставлял бы команду исполняемой. Экранируется любой ведущий `/`, без попытки угадать,
 * что GitLab сочтёт именем команды: расхождение с его разбором и было бы обходом.
 * Цена — видимый `\/` в начале строки кода.
 */
export function neutralizeQuickActions(body: string): string {
  return body
    .split('\n')
    .map((line) => line.replace(/^(\s*)\//, '$1\\/'))
    .join('\n');
}
